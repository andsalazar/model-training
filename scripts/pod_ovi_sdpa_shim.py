"""Install a `flash_attn` shim backed by PyTorch SDPA.

Why this exists
---------------
Ovi hard-asserts ``FLASH_ATTN_2_AVAILABLE`` and calls exactly one function from it,
``flash_attn_varlen_func``. Compiling real FlashAttention on this pod is blocked: the
container has a 62GB cgroup memory limit with no swap, and each nvcc translation unit
for flash-attention peaks around 15GB, so even ``MAX_JOBS=4`` gets OOM-killed (the log
shows bare ``Killed`` lines with no compiler error).

PyTorch's ``scaled_dot_product_attention`` dispatches to a fused memory-efficient
kernel on Blackwell, so it is a legitimate substitute for a *measurement* experiment.
It is not bit-identical to FlashAttention, and that matters for the claim being made:
the metric question is "does entropy separate a degrading rollout from a healthy one",
which is a property of the generated frames, not of the attention kernel. Any
numerical difference between SDPA and FA2 is far smaller than the collapse signal the
metric is looking for.

This shim is therefore appropriate for Stage 6's metric feasibility check and would
NOT be appropriate for a final quality claim about Ovi's output.

The shim implements the varlen contract
---------------------------------------
``flash_attn_varlen_func`` takes packed sequences: q/k/v are ``[total_tokens, heads,
dim]`` with ``cu_seqlens`` giving the boundaries. SDPA wants padded ``[batch, heads,
seq, dim]``. The shim unpacks, runs SDPA per sequence, and repacks. Sequences in a
batch can have different lengths, so it loops rather than padding — slower, but this
is a correctness-first substitute.
"""

from __future__ import annotations

import sys
from pathlib import Path

SHIM = '''"""SDPA-backed stand-in for flash_attn's varlen entry point.

Generated by pod_ovi_sdpa_shim.py. Not real FlashAttention - see that script's
docstring for why this substitution is acceptable for a measurement experiment and
not for a final quality claim.
"""

import torch
import torch.nn.functional as F

__version__ = "0.0.0-sdpa-shim"


def flash_attn_varlen_func(
    q,
    k,
    v,
    cu_seqlens_q,
    cu_seqlens_k,
    max_seqlen_q=None,
    max_seqlen_k=None,
    dropout_p=0.0,
    softmax_scale=None,
    causal=False,
    window_size=(-1, -1),
    softcap=0.0,
    alibi_slopes=None,
    deterministic=False,
    return_attn_probs=False,
):
    """Packed-sequence attention via torch SDPA.

    q: [total_q, nheads, headdim]
    k: [total_k, nheads_k, headdim]
    v: [total_k, nheads_k, headdim]
    cu_seqlens_*: [batch+1] int32 cumulative sequence lengths
    """
    assert q.dim() == 3, f"expected [total, heads, dim], got {tuple(q.shape)}"
    assert cu_seqlens_q is not None and cu_seqlens_k is not None

    q_cu = cu_seqlens_q.to(torch.int64).cpu()
    k_cu = cu_seqlens_k.to(torch.int64).cpu()
    batch = q_cu.numel() - 1

    nheads = q.shape[1]
    nheads_k = k.shape[1]
    # SDPA needs matching head counts; repeat k/v for grouped-query attention.
    repeat = nheads // nheads_k if nheads_k and nheads % nheads_k == 0 else 1

    outputs = []
    for i in range(batch):
        qs, qe = int(q_cu[i]), int(q_cu[i + 1])
        ks, ke = int(k_cu[i]), int(k_cu[i + 1])
        if qe <= qs:
            continue
        qi = q[qs:qe].transpose(0, 1).unsqueeze(0)      # [1, H, Lq, D]
        ki = k[ks:ke].transpose(0, 1).unsqueeze(0)      # [1, Hk, Lk, D]
        vi = v[ks:ke].transpose(0, 1).unsqueeze(0)
        if repeat > 1:
            ki = ki.repeat_interleave(repeat, dim=1)
            vi = vi.repeat_interleave(repeat, dim=1)
        out = F.scaled_dot_product_attention(
            qi, ki, vi,
            dropout_p=dropout_p if q.requires_grad else 0.0,
            is_causal=causal,
            scale=softmax_scale,
        )
        outputs.append(out.squeeze(0).transpose(0, 1))  # [Lq, H, D]

    if not outputs:
        return q.new_zeros((0, nheads, v.shape[-1]))
    return torch.cat(outputs, dim=0)


def flash_attn_func(q, k, v, dropout_p=0.0, softmax_scale=None, causal=False, **kw):
    """Dense attention via SDPA, for completeness."""
    qi = q.transpose(1, 2)
    ki = k.transpose(1, 2)
    vi = v.transpose(1, 2)
    out = F.scaled_dot_product_attention(
        qi, ki, vi, dropout_p=dropout_p, is_causal=causal, scale=softmax_scale
    )
    return out.transpose(1, 2)
'''


def main() -> None:
    venv = Path(sys.argv[1] if len(sys.argv) > 1 else "/workspace/ovi-env")
    target = venv / "lib" / "python3.12" / "site-packages" / "flash_attn"
    target.mkdir(parents=True, exist_ok=True)
    (target / "__init__.py").write_text(SHIM)
    print(f"wrote {target / '__init__.py'}")

    # Verify the shim actually runs a kernel rather than merely importing.
    import subprocess

    check = subprocess.run(
        [
            str(venv / "bin" / "python"),
            "-c",
            (
                "import torch, flash_attn;"
                "print('shim', flash_attn.__version__);"
                "q=torch.randn(8,4,64,device='cuda',dtype=torch.bfloat16);"
                "cu=torch.tensor([0,8],dtype=torch.int32,device='cuda');"
                "o=flash_attn.flash_attn_varlen_func(q,q,q,cu,cu,8,8);"
                "torch.cuda.synchronize();"
                "print('varlen OK', tuple(o.shape))"
            ),
        ],
        capture_output=True,
        text=True,
    )
    print(check.stdout.strip())
    if check.returncode != 0:
        print(check.stderr[-1500:])
        raise SystemExit(1)


if __name__ == "__main__":
    main()
